#!/usr/bin/env node
// Regenerates app/src/home/navigator/digest.md: the documentation the Navigator answers from.
// It copies chosen sections of Bridge's own docs and of the public Orka docs, keeping each
// section's source path so an answer can name the page it drew on.
//
//   node scripts/navigator-digest.mjs --orka ../orka [--check]
//
// --orka points at a checkout of github.com/orka-agents/orka; the script only reads it.
// --check exits non-zero when the committed digest differs from what would be written.
// app/src/home/navigator/size.test.ts keeps the result inside the Agent create budget.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'app/src/home/navigator/digest.md');
const args = process.argv.slice(2);
const orkaAt = args.indexOf('--orka');
if (orkaAt < 0 || !args[orkaAt + 1]) {
  console.error('Usage: node scripts/navigator-digest.mjs --orka <path to an orka checkout> [--check]');
  process.exit(2);
}
const orka = resolve(args[orkaAt + 1]);
const check = args.includes('--check');

// [source, file, headings to keep ('' is the text before the first ## heading), characters per section]
const bridge = [
  ['README.md', ['What works today', 'Where Bridge is going', 'How it works', "What's next"], 1800],
  ['docs/glossary.md', ['', 'Use the words together'], 2400],
  ['docs/shared-clusters.md', ['Decision', 'A Task creator can indirectly use namespace Secrets', 'RBAC is additive and not field-aware'], 1200],
];
const orkaDocs = [
  ['getting-started.md', ['', 'Mental Model', '2. Create an Agent', '3. Run a Task', '4. Check the Result'], 1500],
  ['concepts/architecture.md', ['Overview', 'Design Decisions', 'Task Lifecycle', 'Multi-Agent Coordination'], 1800],
  ['concepts/configuration.md', ['Task', 'Agent', 'Skill', 'Tool', 'RepositoryMonitor'], 1600],
  ['concepts/memory.md', ['', 'Memory proposal lifecycle', 'Safety model'], 1300],
  ['concepts/security.md', ['Secret Management', 'Namespace Scoping'], 1000],
  ['guides/repository-monitors.md', ['', 'What It Does'], 1800],
  ['guides/autonomous-tasks.md', ['Overview'], 1000],
  ['guides/multi-agent-coordination.md', [''], 1200],
  ['concepts/agent-runtimes.md', [''], 1400],
];

// Sections are split on ## and ### headings; fenced code is kept whole or cut at a line.
function sections(text) {
  const result = new Map();
  let heading = ''; let body = []; let fenced = false;
  for (const line of text.replace(/^---\n[\s\S]*?\n---\n/, '').split('\n')) {
    if (/^\s*```/.test(line)) fenced = !fenced;
    const match = !fenced && /^#{2,3} (.+)$/.exec(line);
    if (match) { result.set(heading, body.join('\n')); heading = match[1].trim(); body = []; continue; }
    if (!fenced && /^# /.test(line)) continue;
    body.push(line);
  }
  result.set(heading, body.join('\n'));
  return result;
}
function trim(text, limit) {
  const clean = text.replace(/<!--[\s\S]*?-->/g, '').replace(/\n{3,}/g, '\n\n').trim();
  if (clean.length <= limit) return clean;
  const cut = clean.slice(0, limit);
  // End on a whole line, and close a code fence the cut left open.
  const whole = cut.slice(0, Math.max(cut.lastIndexOf('\n'), 0)) || cut;
  return ((whole.match(/```/g) ?? []).length % 2 ? `${whole}\n\`\`\`` : whole) + '\n…';
}
function digestOf(base, label, list) {
  const parts = [];
  for (const [file, headings, limit] of list) {
    const found = sections(readFileSync(join(base, file), 'utf8'));
    for (const heading of headings) {
      if (!found.has(heading)) throw Error(`${label}${file}: no section "${heading}"`);
      const body = trim(found.get(heading), limit);
      if (!body) continue;
      parts.push(`## ${heading || title(base, file)}\nSource: ${label}${file}${heading ? `#${anchor(heading)}` : ''}\n\n${body}`);
    }
  }
  return parts;
}
function title(base, file) { return /^# (.+)$/m.exec(readFileSync(join(base, file), 'utf8'))?.[1].trim() ?? file; }
function anchor(heading) { return heading.toLowerCase().replace(/[^a-z0-9 -]/g, '').trim().replace(/\s+/g, '-'); }

const revision = execFileSync('git', ['-C', orka, 'rev-parse', '--short=12', 'HEAD'], { encoding: 'utf8' }).trim();
const text = [
  '# Documentation digest',
  '',
  'Generated by scripts/navigator-digest.mjs; do not edit by hand. Sources starting `bridge:` are this',
  `app's own docs. Sources starting \`orka:\` are excerpts of the Orka documentation (website/docs at ${revision},`,
  'github.com/orka-agents/orka, MIT License, Copyright (c) Microsoft Corporation). Each section names its source.',
  '',
  ...digestOf(join(root), 'bridge:', bridge).flatMap(part => [part, '']),
  ...digestOf(join(orka, 'website/docs'), 'orka:', orkaDocs).flatMap(part => [part, '']),
].join('\n').trimEnd() + '\n';

if (check) {
  const current = readFileSync(out, 'utf8');
  if (current !== text) { console.error('app/src/home/navigator/digest.md is out of date. Run scripts/navigator-digest.mjs.'); process.exit(1); }
  console.log('digest is current');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${Buffer.byteLength(text)} bytes)`);
}
